━━━━━━━━━━━━━━━━━━━━━━
【図解】直接基礎の種類
　形式｜内容｜適用
　フーチング基礎｜柱ごとに独立した底板★｜支持力に余裕がある場合
　複合フーチング基礎｜複数の柱を1つの底板で支える｜柱間隔が狭い場合
　べた基礎｜建物全面を1枚の版で支える★｜荷重が大きく地盤が弱い場合★
　布基礎（連続フーチング）｜壁に沿って連続する底板｜壁式構造

・支持層が浅く（一般に地表から数m程度以内）、
　十分な支持力が期待できる場合に採用する★
・根入れは、凍結深度・洗掘深さ・地表面の
　変動を考慮して決定する★

